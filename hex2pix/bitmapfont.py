GLYPHS = dict((char, tuple(rows.split(" ")))
              for char, rows in _ROW_PATTERNS.items())

FALLBACK = "?"


def glyph_rows(char):
    """The seven rows of `char`; unknown characters fall back to `?`."""
    rows = GLYPHS.get(char)
    if rows is None:
        rows = GLYPHS[FALLBACK]
    return rows


def _whole(value, low, high, default):
    try:
        value = int(value)
    except (TypeError, ValueError):
        return default
    return max(low, min(high, value))


def text_points(text, scale=1, spacing=1):
    """Ink pixels for one line, relative to the top-left corner.

    `scale` enlarges every glyph pixel to a `scale x scale` block and `spacing`
    adds blank columns between glyphs, both in whole pixels.
    """
    scale = _whole(scale, 1, 64, 1)
    spacing = _whole(spacing, 0, 64, 0)
    points = []
    cursor = 0
    for char in text:
        for row_index, row in enumerate(glyph_rows(char)):
            for column, bit in enumerate(row):
                if bit != "1":
                    continue
                left = cursor + column * scale
                top = row_index * scale
                for dy in range(scale):
                    for dx in range(scale):
                        points.append((left + dx, top + dy))
        cursor += (GLYPH_WIDTH + spacing) * scale
    return points


def text_size(text, scale=1, spacing=1):
    """The inked (width, height) of `text`; (0, 0) when nothing is inked."""
    points = text_points(text, scale, spacing)
    if not points:
        return (0, 0)
    return (max(x for x, _ in points) + 1, max(y for _, y in points) + 1)


def line_height(scale=1, spacing=1):
    """Rows a single line occupies, including the blank row under it."""
    return GLYPH_HEIGHT * _whole(scale, 1, 64, 1)
